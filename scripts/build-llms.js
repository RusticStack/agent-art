#!/usr/bin/env node
// Builds llms-full.txt: the whole agent-facing reference in one plain-text file, generated from the
// sources an MCP client sees (server instructions, tool schemas, art_help topics and skills), so it
// cannot drift from the code. test/llms.test.js regenerates it in memory and compares.
//
//   npm run docs:llms          (node scripts/build-llms.js [--out FILE])
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { INSTRUCTIONS, TOOLS } from '../src/mcp.js';
import { TOPICS, helpText } from '../src/docs.js';
import { SKILLS, skillText, skillDescription } from '../src/skills.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LLMS_FULL = path.join(ROOT, 'llms-full.txt');

/** One schema property as compact text: `name (type, required): enum a|b; default x; description`. */
function describeParam(name, p = {}, required = false) {
  const types = [].concat(p.type ?? (p.enum ? [] : 'any'));
  if (types[0] === 'array' && p.items?.type) types[0] = `array of ${[].concat(p.items.type).join('|')}`;
  const head = `${name} (${[types.join('|') || 'enum', required && 'required'].filter(Boolean).join(', ')})`;
  const bits = [];
  if (p.enum) bits.push(`one of ${p.enum.join(' | ')}`);
  if (p.items?.enum) bits.push(`items: ${p.items.enum.length > 12 ? `${p.items.enum.length} names (art_help {op})` : p.items.enum.join(' | ')}`);
  if (p.default !== undefined) bits.push(`default ${JSON.stringify(p.default)}`);
  if (p.minimum !== undefined || p.maximum !== undefined) bits.push(`range ${p.minimum ?? ''}..${p.maximum ?? ''}`);
  if (p.description) bits.push(p.description);
  return `- ${head}${bits.length ? `: ${bits.join('; ')}` : ''}`;
}

function toolSection(t) {
  const s = t.inputSchema || {};
  const req = new Set(s.required || []);
  const props = Object.entries(s.properties || {});
  const lines = [`### ${t.name}`, '', t.description, ''];
  lines.push(props.length ? 'Parameters:' : 'Parameters: none');
  for (const [k, p] of props) lines.push(describeParam(k, p, req.has(k)));
  return lines.join('\n');
}

/** The full llms-full.txt text (deterministic: same sources = same bytes). */
export function buildLlmsFull() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  const topics = Object.keys(TOPICS);
  const skills = Object.keys(SKILLS);
  const out = [
    `# Agent Art ${pkg.version}: full reference for AI agents`,
    '',
    `> ${pkg.description}`,
    '',
    'Generated by scripts/build-llms.js from src/mcp.js (server instructions and tool schemas), src/docs.js (art_help topics and draw commands) and src/skills.js (skills). Do not edit by hand: run `npm run docs:llms`.',
    `Package: ${pkg.name} (npm). Repository: https://github.com/RusticStack/agent-art. Install for Claude Code: claude mcp add agent-art -s user -- npx -y ${pkg.name} mcp`,
    '',
    'Contents: 1. MCP server instructions; 2. Tools (' + TOOLS.length + '); 3. Draw commands (art_draw ops); 4. Help topics (' + topics.length + '); 5. Skills (' + skills.length + ').',
    '',
    '## 1. MCP server instructions',
    '',
    INSTRUCTIONS,
    '',
    '## 2. Tools',
    '',
    `Every tool takes one JSON object. Tools with an "action" parameter dispatch on it. Keys outside the schema are passed through to the engine too: the nested options are documented in the tool description and in art_help.`,
    '',
    TOOLS.map(toolSection).join('\n\n'),
    '',
    '## 3. Draw commands (art_draw ops)',
    '',
    'Each is {"op":"<name>", ...fields} inside art_draw commands. Same text as art_help {topic:"ops"}.',
    '',
    helpText({ topic: 'ops' }),
    '',
    '## 4. Help topics',
    '',
    `art_help {topic:"<name>"} returns each of these. Topics: ${topics.join(', ')}.`,
    '',
    topics.map((k) => `### Topic: ${k}\n\n${TOPICS[k]}`).join('\n\n'),
    '',
    '## 5. Skills',
    '',
    'art_help {skill:"<name>"} returns each of these; they are also MCP prompts, and `agent-art skills --out DIR` writes them as DIR/agent-art-<name>/SKILL.md.',
    '',
    skills.map((k) => `### Skill: ${k}\n\nDescription: ${skillDescription(k)}\n\n${skillText(k)}`).join('\n\n'),
    '',
  ];
  return out.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const i = process.argv.indexOf('--out');
  const file = i > 0 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : LLMS_FULL;
  const text = buildLlmsFull();
  fs.writeFileSync(file, text);
  console.log(`wrote ${path.relative(process.cwd(), file) || file} (${text.length} chars, ${TOOLS.length} tools, ${Object.keys(TOPICS).length} topics, ${Object.keys(SKILLS).length} skills)`);
}
